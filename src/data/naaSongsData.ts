export function convertNaaSongToSong(track: NaaSongsTrack): Song {
  return {
    id: track.id,
    title: track.title,
    artist: track.artist,
    album: `${track.movie} [${track.portalSource} 320Kbps HD]`,
    durationMs: track.durationMs,
    bpm: track.bpm,
    key: track.key,
    genre: track.genre,
    gradientStart: track.gradientStart,
    gradientEnd: track.gradientEnd,
    isDolbyAtmos: true,
    isHiResLossless: true,
    bitDepth: 24,
    sampleRateKhz: 96,
    sourcePortal: track.portalSource,
    coverImage: track.albumArt,
    year: track.year,
    movieName: track.movie,
    audioUrl: getNaaSongAudioUrl(track),
    stems: [
      {
        id: `${track.id}_vocals`,
        name: `${track.title} (Lead Vocals)`,
        category: StemCategory.MAIN_MELODY,
        durationMs: track.durationMs,
        waveformPoints: Array.from({ length: 48 }, (_, i) => 0.3 + 0.6 * Math.abs(Math.sin(i * 0.4))),
        isRingtoneRecommended: true,
        description: `Isolated vocal stem by ${track.artist}. Perfect for custom ringtone extraction.`
      },
      {
        id: `${track.id}_dappu_bass`,
        name: 'South Indian Bass & 808',
        category: StemCategory.BASSLINE_GROOVE,
        durationMs: track.durationMs,
        waveformPoints: Array.from({ length: 48 }, (_, i) => 0.2 + 0.7 * Math.abs(Math.cos(i * 0.3))),
        isRingtoneRecommended: false,
        description: 'Sub-bass frequencies tuned for Dolby Atmos subwoofer response.'
      },
      {
        id: `${track.id}_rhythm`,
        name: 'Dappu & Percussions',
        category: StemCategory.DRUMS_PERCUSSION,
        durationMs: track.durationMs,
        waveformPoints: Array.from({ length: 48 }, (_, i) => 0.4 + 0.5 * Math.sin(i * 0.7)),
        isRingtoneRecommended: true,
        description: 'Authentic Indian folk drums, kicks, and high-energy claps.'
      },
      {
        id: `${track.id}_pad`,
        name: 'Cinematic Orchestral Pad',
        category: StemCategory.AMBIENT_PAD,
        durationMs: track.durationMs,
        waveformPoints: Array.from({ length: 48 }, (_, i) => 0.2 + 0.4 * Math.sin(i * 0.2)),
        isRingtoneRecommended: false,
        description: 'Binaural 360-degree reverberant string section.'
      },
      {
        id: `${track.id}_solo`,
        name: 'Nadaswaram / Climax Hook',
        category: StemCategory.CLIMAX_SOLO,
        durationMs: track.durationMs,
        waveformPoints: Array.from({ length: 48 }, (_, i) => 0.3 + 0.65 * Math.abs(Math.sin(i * 0.55))),
        isRingtoneRecommended: true,
        description: 'The peak climax melody hook segment optimized for phone ringtones.'
      }
    ],
    lyrics: getFullLyricsForTrack(track.title, track.artist, track.movie, track.durationMs),
    description: `Original Telugu Soundtrack from ${track.movie}. Composed by ${track.musicDirector}, featuring ${track.artist}. Sourced from ${track.portalSource} (${track.bitrate}).`
  };
}
